const norm = (t) => String(t || '').replace(/[*:]/g, '').replace(/\s+/g, ' ').trim().toLowerCase();
export const hiFor = (t) => HI[norm(t)];
// Skip help lines that only repeat the English word (e.g. "Students", "Washrooms → Washroom")
const same = (a, b) => { const x = norm(a).replace(/s$/, ''); const y = norm(b).replace(/s$/, ''); return x === y || x.startsWith(y + ' (') || y.startsWith(x + ' ('); };
export const hinglishOn = () => { try { return localStorage.getItem('hinglish') !== 'off'; } catch (e) { return true; } };
export function setHinglish(on) { try { localStorage.setItem('hinglish', on ? 'on' : 'off'); } catch (e) { /* ignore */ } }

function firstText(el) {
  for (const n of el.childNodes) { if (n.nodeType === 3 && n.textContent.trim()) return n; }
  return null;
}
function addLine(el, text) {
  const s = document.createElement('span');
  s.className = 'hi'; s.textContent = text;
  el.appendChild(s);
}

// Apply to a root element. Safe to call repeatedly.
export function applyHinglish(root) {
  if (!hinglishOn() || !root) return;
  root.querySelectorAll('.fld > label, .fld > .lab, .fld .lab > label, .chk, .yn label span, .modebox b, .tile b, .checklist .row > span:first-child, .kpi .l, button.btn, a.btn, .tabs a, .seg button, .nav a span, h1').forEach((el) => {
    if (el.dataset.hi || el.classList.contains('hi') || el.closest('.hi')) return;
    el.dataset.hi = '1';
    const tn = el.matches('.chk') ? [...el.childNodes].filter((n) => n.nodeType === 3 && n.textContent.trim()).pop() : firstText(el);
    const src = tn ? tn.textContent : el.textContent;
    const h = hiFor(src);
    if (!h || same(h, src)) return;
    if (el.matches('button.btn, a.btn, .tabs a, .seg button')) { el.title = h; if (el.matches('.lg')) addLine(el, h); return; }
    addLine(el, h);
  });
  root.querySelectorAll('select option').forEach((o) => {
    if (o.dataset.hi) return;
    o.dataset.hi = '1';
    const h = hiFor(o.textContent);
    if (h && !same(h, o.textContent)) o.textContent = `${o.textContent} — ${h}`;
  });
}

let observer = null;
export function watchHinglish() {
  if (observer) return;
  let pending = false;
  observer = new MutationObserver(() => {
    if (pending) return;
    pending = true;
    requestAnimationFrame(() => { pending = false; applyHinglish(document.body); });
  });
  observer.observe(document.body, { childList: true, subtree: true });
  applyHinglish(document.body);
}
